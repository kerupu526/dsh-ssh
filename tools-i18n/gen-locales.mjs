// Generates src/client/locales.ts from translations.json, keeping only keys the transformed sources use.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const translations = JSON.parse(readFileSync('tools-i18n/translations.json', 'utf8'))
const sources = readdirSync('src/client')
  .filter((f) => /\.(ts|tsx)$/.test(f) && f !== 'locales.ts')
  .map((f) => readFileSync(join('src/client', f), 'utf8'))
  .join('\n')

const used = Object.keys(translations).filter((key) => sources.includes(JSON.stringify(key)))
const unused = Object.keys(translations).filter((key) => !used.includes(key))
console.log('used keys:', used.length, 'unused (dropped):', unused.length, unused.map((k) => JSON.stringify(k)).join(', '))

const block = (lang) => used.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(translations[key][lang])},`).join('\n')

const source = `// Translation dictionaries for dsh-ssh's client UI, keyed by the original Chinese text.
// Generated by tools-i18n/gen-locales.mjs from tools-i18n/translations.json. Do not edit by hand.
// A key missing from a language falls back to the original text through the locale service.

export const en: Record<string, string> = {
${block('en')}
}

export const ko: Record<string, string> = {
${block('ko')}
}
`
writeFileSync('src/client/locales.ts', source, 'utf8')
console.log('wrote src/client/locales.ts')
